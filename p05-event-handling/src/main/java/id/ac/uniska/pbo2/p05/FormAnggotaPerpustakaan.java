    /** Menampilkan jumlah digit NPM. Ditulis sekali, dipanggil dari beberapa tempat. */
private void perbaruiJumlahDigit() {
    int jumlah = npmField.getText().trim().length();
    digitLabel.setText(jumlah + " dari 10 digit");
}
