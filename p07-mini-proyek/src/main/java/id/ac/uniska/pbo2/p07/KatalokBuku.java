    private Buku buatBuku(String kode, String judul, int tahun, String penulis,
        boolean dipinjam) {
    Buku buku = new Buku(kode, judul, tahun, penulis);
    if (dipinjam) {
        buku.pinjam(); // buku baru otomatis Tersedia
    }
    return buku;
}

